-- 1. Estados de Venezuela y su relación con los taekwondistas.
-- 2. Borrado lógico (soft delete): columna eliminado_en en todas las tablas.
--    Las restricciones UNIQUE pasan a índices parciales sobre los registros
--    activos, para poder volver a crear un nombre que se eliminó antes.

CREATE TABLE IF NOT EXISTS estados (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(50) NOT NULL
);

-- Nullable en la base para no romper los taekwondistas ya cargados; la API
-- lo exige al crear o editar.
ALTER TABLE taekwondistas ADD COLUMN IF NOT EXISTS id_estado integer REFERENCES estados (id);
CREATE INDEX IF NOT EXISTS taekwondistas_id_estado_idx ON taekwondistas (id_estado);

ALTER TABLE usuarios      ADD COLUMN IF NOT EXISTS eliminado_en timestamptz;
ALTER TABLE academias     ADD COLUMN IF NOT EXISTS eliminado_en timestamptz;
ALTER TABLE categorias    ADD COLUMN IF NOT EXISTS eliminado_en timestamptz;
ALTER TABLE cintas        ADD COLUMN IF NOT EXISTS eliminado_en timestamptz;
ALTER TABLE competencias  ADD COLUMN IF NOT EXISTS eliminado_en timestamptz;
ALTER TABLE danes         ADD COLUMN IF NOT EXISTS eliminado_en timestamptz;
ALTER TABLE estados       ADD COLUMN IF NOT EXISTS eliminado_en timestamptz;
ALTER TABLE taekwondistas ADD COLUMN IF NOT EXISTS eliminado_en timestamptz;
ALTER TABLE combates      ADD COLUMN IF NOT EXISTS eliminado_en timestamptz;

ALTER TABLE usuarios  DROP CONSTRAINT IF EXISTS usuarios_email_key;
ALTER TABLE academias DROP CONSTRAINT IF EXISTS academias_nombre_key;
ALTER TABLE cintas    DROP CONSTRAINT IF EXISTS cintas_nombre_key;
ALTER TABLE cintas    DROP CONSTRAINT IF EXISTS cintas_orden_key;
ALTER TABLE danes     DROP CONSTRAINT IF EXISTS danes_nombre_key;
ALTER TABLE danes     DROP CONSTRAINT IF EXISTS danes_numero_key;

CREATE UNIQUE INDEX IF NOT EXISTS usuarios_email_activo_key   ON usuarios (email)   WHERE eliminado_en IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS academias_nombre_activo_key ON academias (nombre) WHERE eliminado_en IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS cintas_nombre_activo_key    ON cintas (nombre)    WHERE eliminado_en IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS cintas_orden_activo_key     ON cintas (orden)     WHERE eliminado_en IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS danes_nombre_activo_key     ON danes (nombre)     WHERE eliminado_en IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS danes_numero_activo_key     ON danes (numero)     WHERE eliminado_en IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS estados_nombre_activo_key   ON estados (nombre)   WHERE eliminado_en IS NULL;
