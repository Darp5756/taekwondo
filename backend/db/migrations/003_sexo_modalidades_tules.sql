-- 1. Sexo en taekwondistas y categorías.
-- 2. Modalidad de la categoría: matsogi (combate) o tul (formas).
--    Matsogi se define por edad y peso; tul por edad y grado, y además guarda
--    cómo se eligen los tules y cuántos jueces votan.
-- 3. Catálogo de tules.
--
-- Todo es compatible con el código anterior: las columnas nuevas son
-- opcionales o tienen valor por defecto, y las que dejan de ser obligatorias
-- solo relajan restricciones.

-- Nullable por los registros anteriores; la API lo exige al crear o editar.
ALTER TABLE taekwondistas ADD COLUMN IF NOT EXISTS sexo varchar(10)
  CHECK (sexo IN ('femenino', 'masculino'));

-- La categoría en la que compite cada atleta pasa a definirse en la
-- inscripción; la del taekwondista queda como "categoría habitual" opcional.
ALTER TABLE taekwondistas ALTER COLUMN id_categoria DROP NOT NULL;

CREATE TABLE IF NOT EXISTS tules (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       varchar(30) NOT NULL,
  orden        smallint NOT NULL CHECK (orden BETWEEN 0 AND 255),
  eliminado_en timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS tules_nombre_activo_key ON tules (nombre) WHERE eliminado_en IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS tules_orden_activo_key  ON tules (orden)  WHERE eliminado_en IS NULL;

ALTER TABLE categorias
  ADD COLUMN IF NOT EXISTS modalidad varchar(10) NOT NULL DEFAULT 'matsogi'
    CHECK (modalidad IN ('matsogi', 'tul')),
  ADD COLUMN IF NOT EXISTS sexo varchar(10) NOT NULL DEFAULT 'mixto'
    CHECK (sexo IN ('femenino', 'masculino', 'mixto')),
  -- Rango de grado (opcional): por cinta, por dan o ambos.
  ADD COLUMN IF NOT EXISTS id_cinta_minima integer REFERENCES cintas (id),
  ADD COLUMN IF NOT EXISTS id_cinta_maxima integer REFERENCES cintas (id),
  ADD COLUMN IF NOT EXISTS id_dan_minimo   integer REFERENCES danes (id),
  ADD COLUMN IF NOT EXISTS id_dan_maximo   integer REFERENCES danes (id),
  -- Configuración de tul.
  ADD COLUMN IF NOT EXISTS id_tul_desde integer REFERENCES tules (id),
  ADD COLUMN IF NOT EXISTS id_tul_hasta integer REFERENCES tules (id),
  ADD COLUMN IF NOT EXISTS tules_por_encuentro smallint NOT NULL DEFAULT 1
    CHECK (tules_por_encuentro BETWEEN 1 AND 2),
  ADD COLUMN IF NOT EXISTS eleccion_tul varchar(10) NOT NULL DEFAULT 'sorteo'
    CHECK (eleccion_tul IN ('sorteo', 'manual')),
  -- Siempre impar: los jueces no votan empate, así siempre hay mayoría.
  ADD COLUMN IF NOT EXISTS jueces smallint NOT NULL DEFAULT 3
    CHECK (jueces BETWEEN 1 AND 9 AND jueces % 2 = 1);

-- El peso solo es obligatorio en matsogi.
ALTER TABLE categorias
  ALTER COLUMN peso_minimo_kg DROP NOT NULL,
  ALTER COLUMN peso_maximo_kg DROP NOT NULL;

DO $$ BEGIN
  ALTER TABLE categorias ADD CONSTRAINT categorias_peso_matsogi
    CHECK (modalidad <> 'matsogi' OR (peso_minimo_kg IS NOT NULL AND peso_maximo_kg IS NOT NULL));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  ALTER TABLE categorias ADD CONSTRAINT categorias_tules_tul
    CHECK (modalidad <> 'tul' OR (id_tul_desde IS NOT NULL AND id_tul_hasta IS NOT NULL));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
