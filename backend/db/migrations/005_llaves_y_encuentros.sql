-- Llaves de eliminación simple y detalle de los encuentros de tul.
--
-- Los combates pasan a referirse a inscripciones en lugar de taekwondistas.
-- Las columnas id_taekwondista_* quedan obsoletas: se dejan (ahora nullable)
-- para que el código anterior siga funcionando mientras se despliega esta
-- versión, y se eliminarán en una migración posterior.

CREATE TABLE IF NOT EXISTS llaves (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_competencia integer NOT NULL REFERENCES competencias (id),
  id_categoria   integer NOT NULL REFERENCES categorias (id),
  tipo           varchar(20) NOT NULL DEFAULT 'eliminacion_simple' CHECK (tipo IN ('eliminacion_simple')),
  tercer_puesto  boolean NOT NULL DEFAULT true,
  separacion     varchar(10) NOT NULL DEFAULT 'ninguna' CHECK (separacion IN ('ninguna', 'academia', 'estado')),
  creado_en      timestamptz NOT NULL DEFAULT now(),
  eliminado_en   timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS llaves_activa_key
  ON llaves (id_competencia, id_categoria) WHERE eliminado_en IS NULL;

ALTER TABLE combates
  ADD COLUMN IF NOT EXISTS id_inscripcion_rojo    integer REFERENCES inscripciones (id),
  ADD COLUMN IF NOT EXISTS id_inscripcion_azul    integer REFERENCES inscripciones (id),
  ADD COLUMN IF NOT EXISTS id_inscripcion_ganador integer REFERENCES inscripciones (id),
  ADD COLUMN IF NOT EXISTS tipo_victoria varchar(20)
    CHECK (tipo_victoria IN ('puntos', 'decision', 'ko', 'abandono', 'descalificacion', 'wo', 'votos', 'bye')),
  -- Posición en la llave (vacías en los combates sueltos).
  ADD COLUMN IF NOT EXISTS id_llave     integer REFERENCES llaves (id),
  ADD COLUMN IF NOT EXISTS numero_ronda smallint,
  ADD COLUMN IF NOT EXISTS posicion     smallint,
  -- Adónde pasan el ganador y el perdedor (este último, al combate por el tercer puesto).
  ADD COLUMN IF NOT EXISTS id_combate_ganador_va_a  integer REFERENCES combates (id),
  ADD COLUMN IF NOT EXISTS esquina_ganador  varchar(4) CHECK (esquina_ganador IN ('rojo', 'azul')),
  ADD COLUMN IF NOT EXISTS id_combate_perdedor_va_a integer REFERENCES combates (id),
  ADD COLUMN IF NOT EXISTS esquina_perdedor varchar(4) CHECK (esquina_perdedor IN ('rojo', 'azul')),
  -- true en los combates que el sistema resolvió solo (bye o W.O. por retiro).
  ADD COLUMN IF NOT EXISTS resuelto_automaticamente boolean NOT NULL DEFAULT false;

-- En una llave, los combates de rondas siguientes existen antes de saber quién los pelea.
ALTER TABLE combates
  ALTER COLUMN id_taekwondista_rojo DROP NOT NULL,
  ALTER COLUMN id_taekwondista_azul DROP NOT NULL;

DO $$ BEGIN
  ALTER TABLE combates ADD CONSTRAINT combates_inscripciones_distintas
    CHECK (id_inscripcion_rojo <> id_inscripcion_azul);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  ALTER TABLE combates ADD CONSTRAINT combates_ganador_inscripcion
    CHECK (id_inscripcion_ganador IS NULL
           OR id_inscripcion_ganador IN (id_inscripcion_rojo, id_inscripcion_azul));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE INDEX IF NOT EXISTS combates_id_llave_idx ON combates (id_llave);

-- Tules ejecutados en un encuentro (los dos competidores ejecutan el mismo).
CREATE TABLE IF NOT EXISTS combate_tules (
  id_combate integer NOT NULL REFERENCES combates (id) ON DELETE CASCADE,
  orden      smallint NOT NULL CHECK (orden BETWEEN 1 AND 2),
  id_tul     integer NOT NULL REFERENCES tules (id),
  PRIMARY KEY (id_combate, orden)
);

-- Voto de cada juez en un encuentro de tul.
CREATE TABLE IF NOT EXISTS combate_votos (
  id_combate integer NOT NULL REFERENCES combates (id) ON DELETE CASCADE,
  juez       smallint NOT NULL CHECK (juez BETWEEN 1 AND 9),
  voto       varchar(4) NOT NULL CHECK (voto IN ('rojo', 'azul')),
  PRIMARY KEY (id_combate, juez)
);

-- Datos existentes: cada participante de un combate pasa a tener su
-- inscripción en esa competencia y categoría. Si todos sus combates estaban
-- eliminados, la inscripción se crea eliminada.
INSERT INTO inscripciones (id_competencia, id_taekwondista, id_categoria, eliminado_en)
SELECT c.id_competencia, p.id_taekwondista, c.id_categoria,
       CASE WHEN bool_or(c.eliminado_en IS NULL) THEN NULL ELSE now() END
FROM combates c
CROSS JOIN LATERAL (VALUES (c.id_taekwondista_rojo), (c.id_taekwondista_azul)) AS p (id_taekwondista)
WHERE p.id_taekwondista IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM inscripciones i
    WHERE i.id_competencia = c.id_competencia
      AND i.id_categoria = c.id_categoria
      AND i.id_taekwondista = p.id_taekwondista)
GROUP BY c.id_competencia, p.id_taekwondista, c.id_categoria;

UPDATE combates c SET
  id_inscripcion_rojo = (
    SELECT i.id FROM inscripciones i
    WHERE i.id_competencia = c.id_competencia AND i.id_categoria = c.id_categoria
      AND i.id_taekwondista = c.id_taekwondista_rojo
    ORDER BY i.eliminado_en NULLS FIRST LIMIT 1),
  id_inscripcion_azul = (
    SELECT i.id FROM inscripciones i
    WHERE i.id_competencia = c.id_competencia AND i.id_categoria = c.id_categoria
      AND i.id_taekwondista = c.id_taekwondista_azul
    ORDER BY i.eliminado_en NULLS FIRST LIMIT 1)
WHERE c.id_inscripcion_rojo IS NULL AND c.id_taekwondista_rojo IS NOT NULL;

UPDATE combates SET id_inscripcion_ganador = CASE id_taekwondista_ganador
    WHEN id_taekwondista_rojo THEN id_inscripcion_rojo
    WHEN id_taekwondista_azul THEN id_inscripcion_azul
  END
WHERE id_inscripcion_ganador IS NULL AND id_taekwondista_ganador IS NOT NULL;
