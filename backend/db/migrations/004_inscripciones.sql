-- Inscripciones: qué taekwondista compite en qué categoría de cada competencia.
-- Un atleta puede inscribirse en una categoría de cada modalidad por
-- competencia (regla validada en la API).

CREATE TABLE IF NOT EXISTS inscripciones (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_competencia     integer NOT NULL REFERENCES competencias (id),
  id_taekwondista    integer NOT NULL REFERENCES taekwondistas (id),
  id_categoria       integer NOT NULL REFERENCES categorias (id),
  -- Peso del pesaje oficial. Si está vacío se usa el peso del taekwondista.
  peso_kg            smallint CHECK (peso_kg BETWEEN 0 AND 255),
  -- Un retirado pierde por W.O. los combates que le queden.
  retirado           boolean NOT NULL DEFAULT false,
  -- Permite inscribir a alguien fuera de los límites de edad, peso, grado o
  -- sexo de la categoría (p. ej. al fusionar categorías con pocos inscritos).
  fuera_de_categoria boolean NOT NULL DEFAULT false,
  creado_en          timestamptz NOT NULL DEFAULT now(),
  eliminado_en       timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS inscripciones_activa_key
  ON inscripciones (id_competencia, id_categoria, id_taekwondista) WHERE eliminado_en IS NULL;
CREATE INDEX IF NOT EXISTS inscripciones_id_taekwondista_idx ON inscripciones (id_taekwondista);
CREATE INDEX IF NOT EXISTS inscripciones_id_categoria_idx ON inscripciones (id_categoria);
