-- Esquema PostgreSQL para la gestión de competencias de Taekwondo ITF.
-- Basado en docs/schema-original.dbml con estos ajustes:
--   * tinyint -> smallint (PostgreSQL no tiene tinyint) con CHECK de rango.
--   * Se corrige la relación combates -> competencias (combates.id_competencia).
--   * Se agregan las FK de combates hacia taekwondistas (rojo, azul y ganador).
--   * Se agrega la tabla usuarios para el login.
-- Es idempotente: se puede ejecutar varias veces sin perder datos.

DO $$ BEGIN
  CREATE TYPE estado_pendiente_en_curso_finalizado_t AS ENUM ('pendiente', 'en_curso', 'finalizado');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS usuarios (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        varchar(100) NOT NULL,
  email         varchar(150) NOT NULL UNIQUE,
  password_hash varchar(100) NOT NULL,
  rol           varchar(20)  NOT NULL DEFAULT 'operador' CHECK (rol IN ('admin', 'operador')),
  activo        boolean      NOT NULL DEFAULT true,
  creado_en     timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS academias (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS categorias (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         varchar(50) NOT NULL,
  edad_minima    smallint NOT NULL CHECK (edad_minima BETWEEN 0 AND 255),
  edad_maxima    smallint NOT NULL CHECK (edad_maxima BETWEEN 0 AND 255),
  peso_minimo_kg smallint NOT NULL CHECK (peso_minimo_kg BETWEEN 0 AND 255),
  peso_maximo_kg smallint NOT NULL CHECK (peso_maximo_kg BETWEEN 0 AND 255),
  CONSTRAINT categorias_rango_edad CHECK (edad_minima <= edad_maxima),
  CONSTRAINT categorias_rango_peso CHECK (peso_minimo_kg <= peso_maximo_kg)
);

CREATE TABLE IF NOT EXISTS cintas (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(30) NOT NULL UNIQUE,
  orden  smallint NOT NULL UNIQUE CHECK (orden BETWEEN 0 AND 255)
);

CREATE TABLE IF NOT EXISTS competencias (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL,
  fecha  date NOT NULL,
  lugar  varchar(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS danes (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(20) NOT NULL UNIQUE,
  numero smallint NOT NULL UNIQUE CHECK (numero BETWEEN 0 AND 255)
);

CREATE TABLE IF NOT EXISTS taekwondistas (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_academia      integer NOT NULL REFERENCES academias (id),
  id_categoria     integer NOT NULL REFERENCES categorias (id),
  id_cinta         integer NOT NULL REFERENCES cintas (id),
  id_dan           integer REFERENCES danes (id),
  nombre           varchar(150) NOT NULL,
  fecha_nacimiento date NOT NULL,
  peso_kg          smallint NOT NULL CHECK (peso_kg BETWEEN 0 AND 255)
);

CREATE TABLE IF NOT EXISTS combates (
  id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_competencia          integer NOT NULL REFERENCES competencias (id),
  id_categoria            integer NOT NULL REFERENCES categorias (id),
  id_taekwondista_rojo    integer NOT NULL REFERENCES taekwondistas (id),
  id_taekwondista_azul    integer NOT NULL REFERENCES taekwondistas (id),
  id_taekwondista_ganador integer REFERENCES taekwondistas (id),
  ronda                   varchar(20) NOT NULL,
  estado                  estado_pendiente_en_curso_finalizado_t NOT NULL DEFAULT 'pendiente',
  puntos_rojo             smallint NOT NULL DEFAULT 0,
  puntos_azul             smallint NOT NULL DEFAULT 0,
  amonestaciones_rojo     smallint NOT NULL DEFAULT 0 CHECK (amonestaciones_rojo >= 0),
  amonestaciones_azul     smallint NOT NULL DEFAULT 0 CHECK (amonestaciones_azul >= 0),
  CONSTRAINT combates_rivales_distintos CHECK (id_taekwondista_rojo <> id_taekwondista_azul),
  CONSTRAINT combates_ganador_valido CHECK (
    id_taekwondista_ganador IS NULL
    OR id_taekwondista_ganador IN (id_taekwondista_rojo, id_taekwondista_azul)
  )
);

CREATE INDEX IF NOT EXISTS taekwondistas_id_academia_idx ON taekwondistas (id_academia);
CREATE INDEX IF NOT EXISTS taekwondistas_id_categoria_idx ON taekwondistas (id_categoria);
CREATE INDEX IF NOT EXISTS combates_id_competencia_idx ON combates (id_competencia);
CREATE INDEX IF NOT EXISTS combates_id_categoria_idx ON combates (id_categoria);
